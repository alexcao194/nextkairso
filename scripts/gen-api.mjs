#!/usr/bin/env node
/**
 * Sinh `lib/api/schema.ts` + `lib/api/endpoints.ts` từ swagger của backend Go.
 *
 *   node scripts/gen-api.mjs [đường-dẫn-swagger.json] [thư-mục-gokairso/internal]
 *
 * - Swagger không có `required`, nên field bắt buộc/tuỳ chọn được suy ra từ tag
 *   `json:"x,omitempty"` / con trỏ trong mã Go (nếu tìm thấy struct tương ứng).
 * - Mỗi operation thành một hàm; tên sinh từ method + path (xem `opName`).
 *   Đọc `lib/api/endpoints.ts` để tra tên, đừng sửa tay — chạy lại script.
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const swaggerPath = process.argv[2] ?? join(root, "../gokairso/docs/swagger.json");
const goDir = process.argv[3] ?? join(root, "../gokairso/internal");
const swagger = JSON.parse(readFileSync(swaggerPath, "utf8"));
const defs = swagger.definitions;

// ── 1. Đọc tag json từ mã Go ────────────────────────────────────────────────
/** structName -> Map(jsonName -> { optional }) */
const goStructs = new Map();
function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) walk(p);
    else if (name.endsWith(".go") && !name.endsWith("_test.go")) scanGo(readFileSync(p, "utf8"));
  }
}
function scanGo(src) {
  const re = /type\s+(\w+)\s+struct\s*\{([\s\S]*?)\n\}/g;
  let m;
  while ((m = re.exec(src))) {
    const fields = goStructs.get(m[1]) ?? new Map();
    for (const line of m[2].split("\n")) {
      const t = line.match(/^\s*\w+\s+([^\s`]+)\s+`[^`]*json:"([^",]+)(,[^"]*)?"/);
      if (!t) continue;
      const optional = /omitempty|omitzero/.test(t[3] ?? "") || t[1].startsWith("*");
      const prev = fields.get(t[2]);
      fields.set(t[2], { optional: prev ? prev.optional || optional : optional });
    }
    goStructs.set(m[1], fields);
  }
}
walk(goDir);

// ── 2. Tên type ─────────────────────────────────────────────────────────────
const isPaged = (k) => k.startsWith("Response-");
const used = new Map();
function cleanName(k) {
  let n = k.replace(/[^A-Za-z0-9_]/g, "_");
  if (n.includes("_")) {
    const last = n.split("_").filter(Boolean).pop();
    n = last;
  }
  return n;
}
const typeName = new Map();
for (const k of Object.keys(defs)) {
  if (isPaged(k)) continue;
  let n = cleanName(k);
  if (used.has(n) && used.get(n) !== k) {
    n = k
      .split(/[^A-Za-z0-9]+/)
      .filter(Boolean)
      .map((s) => s[0].toUpperCase() + s.slice(1))
      .join("");
  }
  used.set(n, k);
  typeName.set(k, n);
}
function pagedItemRef(k) {
  const d = defs[k];
  return d?.properties?.items?.items?.$ref?.split("/").pop();
}

// ── 3. Render type ──────────────────────────────────────────────────────────
function ref(k) {
  if (isPaged(k)) {
    const item = pagedItemRef(k);
    return `Paged<${item ? typeName.get(item) : "unknown"}>`;
  }
  return typeName.get(k) ?? "unknown";
}
function render(s) {
  if (!s) return "unknown";
  if (s.$ref) return ref(s.$ref.split("/").pop());
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (s.allOf?.length === 1) return render(s.allOf[0]);
  switch (s.type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "array":
      return `${wrap(render(s.items))}[]`;
    case "object": {
      if (s.properties) return inlineObject(s);
      if (s.additionalProperties) {
        const ap = s.additionalProperties;
        return `Record<string, ${ap === true ? "unknown" : render(ap)}>`;
      }
      return "Record<string, unknown>";
    }
    default:
      return "unknown";
  }
}
const wrap = (t) => (/[|&]/.test(t) && !t.startsWith("Paged<") ? `(${t})` : t);
function inlineObject(s) {
  const body = Object.entries(s.properties)
    .map(([n, p]) => `${JSON.stringify(n).replace(/^"(\w+)"$/, "$1")}?: ${render(p)}`)
    .join("; ");
  return `{ ${body} }`;
}

// ── 4. schema.ts ────────────────────────────────────────────────────────────
let schema = `// GENERATED by scripts/gen-api.mjs từ gokairso/docs/swagger.json — KHÔNG sửa tay.
/* eslint-disable */

/** Envelope phân trang chung của backend. */
export interface Paged<T> {
  items: T[];
  page: number;
  limit: number;
  hasMore: boolean;
}

`;
for (const [k, d] of Object.entries(defs)) {
  if (isPaged(k)) continue;
  const name = typeName.get(k);
  if (d.enum) {
    schema += `export type ${name} = ${d.enum.map((v) => JSON.stringify(v)).join(" | ")};\n\n`;
    continue;
  }
  if (d.type !== "object" || !d.properties) {
    schema += `export type ${name} = ${render(d)};\n\n`;
    continue;
  }
  const goFields = goStructs.get(name) ?? goStructs.get(k);
  const reqList = new Set(d.required ?? []);
  schema += `export interface ${name} {\n`;
  for (const [pn, p] of Object.entries(d.properties)) {
    const gf = goFields?.get(pn);
    const optional = reqList.has(pn) ? false : gf ? gf.optional : true;
    const desc = p.description?.split("\n")[0];
    if (desc) schema += `  /** ${desc.replace(/\*\//g, "")} */\n`;
    const key = /^[A-Za-z_]\w*$/.test(pn) ? pn : JSON.stringify(pn);
    schema += `  ${key}${optional ? "?" : ""}: ${render(p)};\n`;
  }
  schema += `}\n\n`;
}
writeFileSync(join(root, "lib/api/schema.ts"), schema);

// ── 5. endpoints.ts ─────────────────────────────────────────────────────────
const singular = (s) =>
  s.endsWith("ies") ? `${s.slice(0, -3)}y` : s.endsWith("sses") ? s.slice(0, -2) : s.endsWith("s") ? s.slice(0, -1) : s;
const pascal = (s) =>
  s
    .split(/[-_]/)
    .map((x) => x[0].toUpperCase() + x.slice(1))
    .join("");

function opName(method, path) {
  const segs = path.split("/").filter(Boolean);
  if (segs[0] === "v1") segs.shift();
  let out = "";
  segs.forEach((seg, i) => {
    if (seg.startsWith("{")) return;
    const nextIsParam = segs[i + 1]?.startsWith("{");
    out += pascal(nextIsParam ? singular(seg) : seg);
  });
  return method.toLowerCase() + out;
}

const ops = [];
const names = new Set();
for (const [path, item] of Object.entries(swagger.paths)) {
  for (const [method, op] of Object.entries(item)) {
    let name = opName(method, path);
    if (names.has(name)) {
      console.warn(`! trùng tên ${name} (${method} ${path}) — thêm hậu tố`);
      name += "2";
    }
    names.add(name);
    ops.push({ name, method: method.toUpperCase(), path, op });
  }
}

const q = (s) => (/^[A-Za-z_]\w*$/.test(s) ? s : JSON.stringify(s));
let ep = `// GENERATED by scripts/gen-api.mjs từ gokairso/docs/swagger.json — KHÔNG sửa tay.
/* eslint-disable */
import { request, type RequestOptions } from "./http";
import type * as S from "./schema";
import type { Paged } from "./schema";

const enc = encodeURIComponent;

`;
const sref = (t) => t.replace(/\b(?!Paged\b|string\b|number\b|boolean\b|unknown\b|Record\b)([A-Z]\w*)\b/g, "S.$1");

for (const { name, method, path, op } of ops) {
  const params = op.parameters ?? [];
  const pathParams = [...path.matchAll(/\{(\w+)\}/g)].map((m) => m[1]);
  const query = params.filter((p) => p.in === "query");
  const body = params.find((p) => p.in === "body");
  const ok = Object.entries(op.responses ?? {}).find(([c]) => c.startsWith("2"))?.[1];
  const ret = ok?.schema ? sref(render(ok.schema)) : "void";

  let qType = "";
  if (query.length) {
    const fields = query
      .map((p) => {
        const t = p.type === "array" ? `${wrap(render({ type: p.items.type }))}[]` : render(p);
        const d = p.description ? `  /** ${p.description.replace(/\*\//g, "").replace(/\n/g, " ")} */\n` : "";
        return `${d}  ${q(p.name)}${p.required ? "" : "?"}: ${t};`;
      })
      .join("\n");
    qType = `export interface ${pascal(name)}Query {\n${fields}\n}\n`;
  }
  if (qType) ep += qType;

  const args = pathParams.map((p) => `${p}: string`);
  if (body) args.push(`body: ${sref(render(body.schema))}`);
  if (query.length) args.push(`query${query.some((p) => p.required) ? "" : "?"}: ${pascal(name)}Query`);
  args.push("opts?: RequestOptions");

  const urlPath = path.replace(/\{(\w+)\}/g, (_, p) => `\${enc(${p})}`);
  const doc = [op.summary, op.description && op.description !== op.summary ? op.description : null]
    .filter(Boolean)
    .map((s) => s.replace(/\*\//g, "").replace(/\n/g, "\n * "))
    .join("\n * ");
  ep += `/** ${method} ${path}${doc ? `\n * ${doc}` : ""} */\n`;
  ep += `export const ${name} = (${args.join(", ")}): Promise<${ret}> =>\n`;
  ep += `  request<${ret}>("${method}", \`${urlPath}\`, { ${body ? "body, " : ""}${query.length ? "query, " : ""}...opts });\n\n`;
}
writeFileSync(join(root, "lib/api/endpoints.ts"), ep);
console.log(`schema: ${typeName.size} type, endpoints: ${ops.length} hàm`);
